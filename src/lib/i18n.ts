export const STRINGS: Record<Lang, Strings> = { en, ar };

export const I18nContext = createContext<{ lang: Lang; t: Strings; setLang: (l: Lang) => void }>({
  lang: 'en',
  t: en,
  setLang: () => {},
});
export const useI18n = () => useContext(I18nContext);

export function fmt(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

export function slotLabel(t: Strings, slot: string): { group: string; item: string } {
  const [station, bean] = slot.split(':');
  if (station === 'espresso') return { group: t.espresso, item: t.espresso_single };
  if (station === 'espresso_hot') return { group: t.espresso, item: t.espresso_hot };
  if (station === 'espresso_cold') return { group: t.espresso, item: t.espresso_cold };
  return { group: t[station as 'hot_drip' | 'iced_drip'], item: t[bean as 'ethiopian' | 'brazilian'] };
}

export function getInitialLang(): Lang {
  try {
    const s = localStorage.getItem('hm_lang');
    if (s === 'en' || s === 'ar') return s;
  } catch {
    /* ignore */
  }
  return navigator.language?.startsWith('ar') ? 'ar' : 'en';
}
